import { lazy } from 'react';
import { Alert, Button, Empty, Skeleton } from 'antd';
import { Link, Navigate, useLocation } from 'react-router-dom';
import { useWorkspace } from './state';
import { findPluginPage, pluginAgentHref } from './pages';

const StandupsPage = lazy(() => import('@/pages/StandupsPage'));
const DashboardPage = lazy(() => import('@/pages/DashboardPage'));
const HumanGanttPage = lazy(() => import('@/pages/HumanGanttPage'));
const WeeklyReportsPage = lazy(() => import('@/pages/WeeklyReportsPage'));
const MeetingSummariesPage = lazy(() => import('@/pages/MeetingSummariesPage'));
const ReleasePage = lazy(() => import('./ReleasePage'));
const KnowledgePage = lazy(() => import('./KnowledgePage'));
const CapturePage = lazy(() => import('./CapturePage'));
const DocumentsPage = lazy(() => import('./DocumentsPage'));
const LibraryPage = lazy(() => import('./LibraryPage'));
const KnowledgeReviewsPage = lazy(() => import('./KnowledgeReviewsPage'));
const ChecksPage = lazy(() => import('./ChecksPage'));
const OpenApiSetupPage = lazy(() => import('./OpenApiSetupPage'));
const OpenApiRunnerPage = lazy(() => import('./OpenApiRunnerPage'));
const McpSetupPage = lazy(() => import('./McpSetupPage'));
const McpRunnerPage = lazy(() => import('./McpRunnerPage'));
const ResearchPage = lazy(() => import('./ResearchPage'));
const RecipesPage = lazy(() => import('./RecipesPage'));

export default function PluginPage() {
  const { data, error, isLoading, mutate } = useWorkspace();
  const { pathname, search } = useLocation();
  if (error) return <div className="workspace-page"><Alert type="error" title="无法确认页面是否已启用" description="检查本地后端连接后重试。" action={<Button onClick={() => mutate()}>重试</Button>} /></div>;
  if (isLoading) return <div className="workspace-page"><Skeleton active /></div>;
  const page = findPluginPage(data?.pages, pathname, search);
  if (page?.view.kind === 'agent') return <Navigate replace to={pluginAgentHref(page.view.capability)} />;
  if (page?.view.kind === 'builtin' && page.view.id === 'standups') return <StandupsPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'dashboard') return <DashboardPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'human-gantt') return <HumanGanttPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'weekly-reports') return <WeeklyReportsPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'meeting-summaries') return <MeetingSummariesPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'release-preparation') return <ReleasePage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'knowledge') return <KnowledgePage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'web-capture') return <CapturePage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'documents') return <DocumentsPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'knowledge-library') return <LibraryPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'knowledge-reviews') return <KnowledgeReviewsPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'plugin-checks') return <ChecksPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'openapi-setup') return <OpenApiSetupPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'openapi-runner') return <OpenApiRunnerPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'mcp-setup') return <McpSetupPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'mcp-runner') return <McpRunnerPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'personal-research') return <ResearchPage />;
  if (page?.view.kind === 'builtin' && page.view.id === 'run-recipes') return <RecipesPage />;
  return <div className="workspace-page"><Empty description={page ? '当前界面版本尚不支持此插件页面' : '此页面不存在或对应插件未启用'}><Link className="primary-link" to="/plugins">查看已装配插件</Link></Empty></div>;
}
